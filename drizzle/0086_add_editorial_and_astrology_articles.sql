ახალი მთვარის დროს ჩვენკენ მოქცეული მხარე თითქმის არ არის მზით განათებული, ამიტომ მთვარე ცაზე ძნელად ჩანს. ეს ციკლის დასაწყისის ასტრონომიული მომენტია. ასტროლოგიურ ენაში მას ხშირად ახალი განზრახვის ან საქმის დაწყების სიმბოლოდ იყენებენ.

თუ ეს სიმბოლო შენთვის სასარგებლოა, შეარჩიე ერთი მცირე, გაზომვადი განზრახვა: „ამ კვირაში ორჯერ საღამოს ათი წუთით გავისეირნებ“. ასეთ გეგმას მთვარე არ ასრულებს — შენ ასრულებ.


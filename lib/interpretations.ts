/**
 * Get a Georgian interpretation paragraph for a single big-three placement.
 * Falls back to a generic sentence if the key is unknown.
 */
export function staticInterpretation(
  kind: BigThreeKind,
  signKey: string
): string {
  const dict = kind === "sun" ? SUN : kind === "moon" ? MOON : ASC;
  return (
    dict[signKey] ??
    `${SIGNS.find((s) => s.key === signKey)?.labelKa ?? signKey} — ${
      SIGN_BLURBS[signKey] ?? "შენი ნიშნის უნიკალური ენერგია."
    }`
  );
}

export function signBlurb(signKey: string): string {
  return SIGN_BLURBS[signKey] ?? "";
}

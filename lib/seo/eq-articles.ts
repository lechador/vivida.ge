export const EQ_ARTICLE_SLUGS: string[] = EQ_ARTICLES.map((a) => a.slug);

export function eqArticleBySlug(slug: string): EqArticle | undefined {
  return EQ_ARTICLES.find((a) => a.slug === slug);
}

export function recommendedEqArticles(domains: EqDomainResult[]): EqArticle[] {
  const sorted = [...domains].sort((a, b) => a.score - b.score);
  const weakKeys = sorted.slice(0, 2).map((d) => d.key);
  const matches = EQ_ARTICLES.filter((article) =>
    article.domains.some((d) => weakKeys.includes(d as EqDomainResult["key"])),
  );
  return (matches.length > 0 ? matches : EQ_ARTICLES).slice(0, 4);
}

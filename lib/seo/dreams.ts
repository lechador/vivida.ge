/** Slug → symbol, for O(1) route lookups. */
export const DREAM_BY_SLUG: Record<string, DreamSymbol> = Object.fromEntries(
  DREAM_SYMBOLS.map((s) => [s.slug, s]),
);

export const ALL_DREAM_SLUGS = DREAM_SYMBOLS.map((s) => s.slug);

export function isDreamSlug(slug: string): boolean {
  return slug in DREAM_BY_SLUG;
}

/**
 * Alphabetical grouping by first Georgian letter. "სიზმრის ახსნა ანბანის
 * მიხედვით" is itself one of the highest-volume phrasings, so the hub is
 * literally built that way rather than as an arbitrary grid.
 */
export function dreamsByLetter(): { letter: string; items: DreamSymbol[] }[] {
  const groups = new Map<string, DreamSymbol[]>();
  for (const s of DREAM_SYMBOLS) {
    const letter = s.titleKa[0];
    const bucket = groups.get(letter);
    if (bucket) bucket.push(s);
    else groups.set(letter, [s]);
  }
  return [...groups.entries()]
    .map(([letter, items]) => ({
      letter,
      items: items.sort((a, b) => a.titleKa.localeCompare(b.titleKa, "ka")),
    }))
    .sort((a, b) => a.letter.localeCompare(b.letter, "ka"));
}


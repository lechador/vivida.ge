export const ALL_DREAM_SLUGS = DREAM_SYMBOLS.map((s) => s.slug);

export const DREAM_BY_SLUG: Record<string, DreamSymbol> = Object.fromEntries(
  DREAM_SYMBOLS.map((s) => [s.slug, s]),
);

export function isDreamSlug(slug: string): boolean {
  return Boolean(DREAM_BY_SLUG[slug]);
}

export function dreamsByLetter(): Array<{ letter: string; items: DreamSymbol[] }> {
  const sorted = [...DREAM_SYMBOLS].sort((a, b) =>
    a.titleKa.localeCompare(b.titleKa, "ka"),
  );
  const groups: Array<{ letter: string; items: DreamSymbol[] }> = [];
  for (const item of sorted) {
    const letter = item.titleKa[0] ?? "•";
    const existing = groups.find((g) => g.letter === letter);
    if (existing) existing.items.push(item);
    else groups.push({ letter, items: [item] });
  }
  return groups;
}


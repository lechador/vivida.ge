export function getThematicHoroscopeAm(
  theme: HoroscopeTheme,
  slug: ZodiacSlug,
): ThematicHoroscopeArmenian {
  const profile = ZODIAC_SIGN_AM[slug];
  const meta = signMetaBySlug(slug);

  if (theme === "love") {
    return {
      main: [
        profile.love,
        `${profile.strengths[0]} և ${profile.strengths[1].toLowerCase()} հատկանիշները հարաբերություններում ձեր առավելությունն են:`,
        `Հիմնական մարտահրավերն է՝ ${profile.challenges[0].toLowerCase()}:`,
      ],
      focus: `Ուշադրություն դարձրեք հուզական անկեղծությանը և փոխադարձ հարգանքին:`,
      watch: `Զգուշացեք ${profile.challenges[1]?.toLowerCase() || "անհասկացողություններից"}:`,
      advice: `Կառուցեք վստահություն բաց հաղորդակցության միջոցով:`,
    };
  }

  if (theme === "finance") {
    const fin = FINANCE_AM[slug];
    return {
      main: [
        fin.focus,
        `Որպես ${meta?.labelAm || slug}՝ ձեր ֆինանսական կայունությունը կախված է կազմակերպվածությունից:`,
        `Ռիսկի գործոն. ${fin.risk}`,
      ],
      focus: fin.focus,
      watch: fin.risk,
      advice: fin.advice,
    };
  }

  return {
    main: [
      profile.career,
      `Աշխատավայրում դուք առանձնանում եք որպես ${profile.strengths[0].toLowerCase()} մասնագետ:`,
      `Աճի համար կարևոր է հաղթահարել ${profile.challenges[0].toLowerCase()}:`,
    ],
    focus: `Զարգացրեք ձեր բնական տաղանդները և մասնագիտական հմտությունները:`,
    watch: `Խուսափեք ${profile.challenges[1]?.toLowerCase() || "գերհոգնածությունից"}:`,
    advice: `Պլանավորեք երկարաժամկետ նպատակներ և քայլ առ քայլ իրագործեք դրանք:`,
  };
}
